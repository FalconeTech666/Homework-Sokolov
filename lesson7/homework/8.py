"""
*
Написать программу калькулятор которая предлагает 
ввести пример для решения пока пользователь не введет команду "стоп"
Программа должна решить пример и запросить следующий.
При вводе команды "стоп" программа завершается.
Поддерживаемые операции: + - * ** /
Пример:
    Введите пример или 'стоп' для завершения: 2 + 2
    Ответ: 4
    Введите пример или 'стоп' для завершения: 16 / 8
    Ответ: 2
    Введите пример или 'стоп' для завершения: 1651+
    Неправильный формат. Пример: '2 + 4'


eval() exec() нельзя
"""

while True:                                            
    inp_str = input("Введите пример или 'стоп' для завершения: ")   

    if inp_str.lower() == "стоп":                     
        break                                         

    blk = inp_str.split()                             # разбиваем строку на части по пробелам

    if len(blk) != 3:                                 # формат должен быть строго: число оператор число
        print("Неправильный формат. Пример: '2 + 4'") # сообщение об ошибке
        continue                                      # возвращаемся к следующему запросу

    a0, sig, b0 = blk                                 # распаковываем: первое число, оператор, второе число

    if not (a0.isdigit() and b0.isdigit()):           # проверяем, что оба числа состоят только из цифр
        print("Неправильный формат. Числа должны быть только цифрами. Пример: '2 + 4'")
        continue                                      # ошибка → новый ввод

    a0 = int(a0)                                     
    b0 = int(b0)                                      

    if sig == "+":                                    # операция сложения
        ans = a0 + b0
    elif sig == "-":                                  # операция вычитания
        ans = a0 - b0
    elif sig == "*":                                  # операция умножения
        ans = a0 * b0
    elif sig == "**":                                 # операция возведения в степень
        ans = a0 ** b0
    elif sig == "/":                                  # операция деления
        if b0 == 0:                                   # проверка деления на ноль
            print("Ошибка: деление на ноль!")         
            continue                                  # запрашиваем новый ввод
        ans = a0 / b0                                 
    else:                                            
        print("Неподдерживаемая операция. Используйте: + - * ** /")
        continue                                      # ошибка → снова запрос

    print("Ответ:", ans)    
